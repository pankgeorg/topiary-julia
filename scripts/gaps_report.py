#!/usr/bin/env python3
"""classify-full.log (JLPARSE_CLASSIFY JSON lines) -> markdown report of the grammar gaps."""
import json, sys
rows = []
for line in open(sys.argv[1]):
    if not line.startswith('CLASSIFY'): continue
    _, id, st, j = line.rstrip('\n').split('\t', 3)
    rows.append(json.loads(j))
def cell(s, n=70):
    s = s.replace('\n', '⏎').replace('|', '\\|')
    return '`' + (s if len(s) <= n else s[:n] + '…') + '`'
gaps = [r for r in rows if r['id'].startswith('jl_gap')]
gaps.sort(key=lambda r: r['id'])
out = []
n_prot = sum(r['status'] == 'protected' for r in gaps)
n_js = sum(r['status'] == 'js_error' for r in gaps)
n_clean = sum(r['status'] == '' for r in gaps)
out.append(f"# Grammar gaps under JuliaSyntax-verified formatting\n")
out.append(f"Generated by `scripts/gaps_report.py` from `JLPARSE_CLASSIFY=1 cargo test --test jlparse_test jl_gap`.\n")
out.append(f"{len(gaps)} known gaps: 22 `grammar_gap` entries of `tests/corpus/expectations.toml` "
           f"(`jl_gap_line_*`) + 47 snippets of `tests/corpus/localized_gaps.toml` (`jl_gap_ts_*`).\n")
out.append(f"- **{n_prot} formatted**: the gap is left verbatim (the smallest JuliaSyntax node around it), "
           f"the rest is formatted, and JuliaSyntax confirms the output means the same. Before: "
           f"Topiary refused the whole input (`Parsing error`).")
out.append(f"- **{n_js} rejected by JuliaSyntax too**, parsed as a file: single characters (`$`, `'`, `.`), "
           f"partial-parse corpus snippets (`+)`, `return)`) and excerpts cut out of a larger construct. "
           f"These now get JuliaSyntax's exact diagnostics instead of tree-sitter's ERROR span.")
if n_clean: out.append(f"- {n_clean} clean (no longer gaps).")
out.append("\n| id | snippet | outcome | left verbatim | output |\n|---|---|---|---|---|")
for r in gaps:
    if r['status'] == 'protected':
        oc = 'formatted'
        vb = ', '.join(cell(v, 40) for v in r['verbatim'])
        o = cell(r['output'])
    elif r['status'] == 'js_error':
        oc = 'JuliaSyntax error'
        vb = ''
        o = cell(r['output'].split(': ', 1)[-1].strip(), 60)
    else:
        oc = 'clean'; vb = ''; o = cell(r['output'])
    out.append(f"| {r['id']} | {cell(r['code'], 50)} | {oc} | {vb} | {o} |")
print('\n'.join(out))
